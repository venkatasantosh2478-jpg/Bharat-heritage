export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => {
    if (typeof window === "undefined") return "en";
    return localStorage.getItem("by-lang") || "en";
  });
  useEffect(() => localStorage.setItem("by-lang", lang), [lang]);

  const t = (key) => {
    if (dict[lang] && dict[lang][key]) return dict[lang][key];
    if (dict.hi && dict.hi[key]) return dict.hi[key];
    return dict.en[key] || key;
  };

  const allCodes = REGIONAL_LANGUAGES.map((l) => l.code);

  return (
    <I18nContext.Provider 
      value={{ 
        lang, 
        setLang, 
        t, 
        langs: allCodes,
        regionalLanguages: REGIONAL_LANGUAGES,
      }}
    >
      {children}
    </I18nContext.Provider>
  );
}

export const useI18n = () => useContext(I18nContext);